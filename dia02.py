# Calculadora
n1 = float(input("Digite o primeiro número: ")) # Solicita ao usuário que digite o primeiro número e converte a entrada para um número de ponto flutuante
n2 = float(input("Digite o segundo número: ")) # Solicita ao usuário que digite o segundo número e converte a entrada para um número de ponto flutuante
soma = n1 + n2 # Calcula a soma dos dois números
sub = n1 - n2 # Calcula a subtração do primeiro número pelo segundo
mult = n1 * n2 # Calcula a multiplicação dos dois números
div = n1 / n2 # Calcula a divisão do primeiro número pelo segundo
print(f"\nResultados:") # Imprime uma mensagem indicando que os resultados serão exibidos
print(f"Soma: {soma}") # Imprime o resultado da soma dos dois números
print(f"Subtração: {sub}") # Imprime o resultado da subtração do primeiro número pelo segundo
print(f"Multiplicação: {mult}") # Imprime o resultado da multiplicação dos dois números
print(f"Divisão: {div}") # Imprime o resultado da divisão do primeiro número pelo segundo