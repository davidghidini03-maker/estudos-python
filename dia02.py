# Calculadora do dia 02
n1 = float(input("Digite o primeiro número: "))
n2 = float(input("Digite o segundo número: "))
soma = n1 + n2
sub = n1 - n2
mult = n1 * n2
div = n1 / n2
print(f"\nResultados:")
print(f"Soma: {soma}")
print(f"Subtração: {sub}")
print(f"Multiplicação: {mult}")
print(f"Divisão: {div}")